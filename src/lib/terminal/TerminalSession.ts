/**
 * TerminalSession - a shell running in a real PTY, emulated by xterm.js (headless).
 *
 * Replaces the hand-written VirtualTerminal parser: xterm handles every escape
 * sequence, wide characters/emoji, truecolor, scroll regions, alternate screen,
 * DECCKM/bracketed paste modes and answers device queries (CPR, DA) that CLIs
 * such as Claude Code wait on.
 */
import { Terminal as XTerm } from "@xterm/headless";
import { Unicode11Addon } from "@xterm/addon-unicode11";
import { encodeKey, type KeyLike } from "./KeyEncoder";

export interface TerminalSessionOptions {
  cwd: string;
  cols: number;
  rows: number;
  /** argv to run; defaults to the user's login shell. */
  command?: string[];
  env?: Record<string, string | undefined>;
  scrollback?: number;
}

type Listener<T extends unknown[] = []> = (...args: T) => void;

export class TerminalSession {
  readonly xterm: XTerm;
  private proc: ReturnType<typeof Bun.spawn> | null = null;
  private opts: TerminalSessionOptions;
  private updateListeners = new Set<Listener>();
  private exitListeners = new Set<Listener<[number | null]>>();
  private titleListeners = new Set<Listener<[string]>>();
  private bellListeners = new Set<Listener>();
  /** Fired when the program starts or exits (not on every output chunk). */
  private statusListeners = new Set<Listener>();
  private disposed = false;
  /** Lines scrolled back from the bottom (0 = following output). */
  private _scrollOffset = 0;
  private _exited = false;
  private _exitCode: number | null = null;
  title = "";

  constructor(opts: TerminalSessionOptions) {
    this.opts = opts;
    this.xterm = new XTerm({
      cols: Math.max(2, opts.cols),
      rows: Math.max(1, opts.rows),
      scrollback: opts.scrollback ?? 10000,
      allowProposedApi: true,
    });
    this.xterm.loadAddon(new Unicode11Addon());
    this.xterm.unicode.activeVersion = "11";
    // Replies generated by the emulator (cursor position reports, device attributes...).
    this.xterm.onData((d) => this.writeToPty(d));
    this.xterm.onBinary((d) => this.writeToPty(Buffer.from(d, "binary")));
    this.xterm.onTitleChange((t) => {
      this.title = t;
      this.titleListeners.forEach((l) => l(t));
    });
    this.xterm.onBell(() => this.bellListeners.forEach((l) => l()));
    this.start();
  }

  get exited() { return this._exited; }
  get cwd() { return this.opts.cwd; }

  /** The shell's current directory (it may have `cd`-ed away from where it started). */
  async currentDir(): Promise<string | null> {
    const pid = this.proc?.pid;
    if (!pid || this._exited) return null;
    try {
      if (process.platform === "linux") return require("fs").readlinkSync(`/proc/${pid}/cwd`);
      const out = await Bun.$`lsof -a -p ${pid} -d cwd -Fn`.quiet().nothrow().text();
      const line = out.split("\n").find((l) => l.startsWith("n"));
      return line ? line.slice(1) : null;
    } catch {
      return null;
    }
  }
  get exitCode() { return this._exitCode; }
  get cols() { return this.xterm.cols; }
  get rows() { return this.xterm.rows; }
  get scrollOffset() { return this._scrollOffset; }
  get applicationCursor() { return this.xterm.modes.applicationCursorKeysMode; }
  get bracketedPaste() { return this.xterm.modes.bracketedPasteMode; }
  get mouseTracking() { return this.xterm.modes.mouseTrackingMode !== "none"; }
  get isAlternateScreen() { return this.xterm.buffer.active.type === "alternate"; }

  private start() {
    const command = this.opts.command ?? [process.env.SHELL || "/bin/zsh", "-l"];
    this._exited = false;
    this._exitCode = null;
    this.statusListeners.forEach((l) => l());
    try {
      this.proc = Bun.spawn(command, {
        cwd: this.opts.cwd,
        env: {
          ...process.env,
          ...this.opts.env,
          TERM: "xterm-256color",
          COLORTERM: "truecolor",
          TERM_PROGRAM: "termide",
        },
        terminal: {
          cols: this.xterm.cols,
          rows: this.xterm.rows,
          data: (_t, data) => {
            if (this.disposed) return;
            // xterm decodes UTF-8 itself, including sequences split across chunks.
            this.xterm.write(data, () => this.emitUpdate());
          },
        },
      });
      this.proc.exited.then((code) => {
        if (this.disposed) return;
        this._exited = true;
        this._exitCode = code;
        this.exitListeners.forEach((l) => l(code));
        this.statusListeners.forEach((l) => l());
        this.emitUpdate();
      });
    } catch (err: any) {
      this._exited = true;
      this.xterm.write(`\x1b[31mFailed to start ${command[0]}: ${err?.message ?? err}\x1b[0m\r\n`, () => this.emitUpdate());
    }
  }

  /** Start the shell again after it exited (keeps scrollback). */
  restart() {
    if (!this._exited || this.disposed) return;
    this.xterm.write("\r\n", () => this.start());
  }

  private emitUpdate() {
    this.updateListeners.forEach((l) => l());
  }

  private writeToPty(data: string | Uint8Array) {
    if (this.disposed || this._exited) return;
    try {
      this.proc?.terminal?.write(data);
    } catch {}
  }

  /** Raw input for the program (typed text, escape sequences). */
  write(data: string) {
    if (!data) return;
    this._scrollOffset = 0;
    this.writeToPty(data);
  }

  /** Encode and send a key; returns false when the key has no terminal meaning. */
  sendKey(key: KeyLike): boolean {
    if (this._exited) {
      if (key.name === "return" && key.eventType !== "release") {
        this.restart();
        return true;
      }
      return false;
    }
    const data = encodeKey(key, { applicationCursor: this.applicationCursor });
    if (data === null) return false;
    this.write(data);
    return true;
  }

  /** Paste text, wrapped in bracketed-paste markers when the program asked for them. */
  paste(text: string) {
    if (!text) return;
    const normalized = text.replace(/\r?\n/g, "\r");
    if (this.bracketedPaste) {
      // Strip markers inside the payload so pasted text can't end the paste early.
      const safe = normalized.replace(/\x1b\[20[01]~/g, "");
      this.write(`\x1b[200~${safe}\x1b[201~`);
    } else {
      this.write(normalized);
    }
  }

  resize(cols: number, rows: number) {
    cols = Math.max(2, Math.floor(cols));
    rows = Math.max(1, Math.floor(rows));
    if (cols === this.xterm.cols && rows === this.xterm.rows) return;
    this.xterm.resize(cols, rows);
    try {
      this.proc?.terminal?.resize(cols, rows);
    } catch {}
    this.clampScroll();
    this.emitUpdate();
  }

  /** Scroll the view through scrollback; positive = towards older output. */
  scrollBy(lines: number) {
    this._scrollOffset += lines;
    this.clampScroll();
    this.emitUpdate();
  }

  scrollToBottom() {
    if (this._scrollOffset === 0) return;
    this._scrollOffset = 0;
    this.emitUpdate();
  }

  private clampScroll() {
    const max = this.xterm.buffer.active.baseY;
    this._scrollOffset = Math.max(0, Math.min(this._scrollOffset, max));
  }

  /** Index of the first buffer line shown in the viewport. */
  get viewportTop() {
    return Math.max(0, this.xterm.buffer.active.baseY - this._scrollOffset);
  }

  /** Scroll so buffer line `line` is visible (roughly a third from the top). */
  revealLine(line: number) {
    const buf = this.xterm.buffer.active;
    const top = Math.max(0, Math.min(buf.baseY, line - Math.floor(this.xterm.rows / 3)));
    this._scrollOffset = buf.baseY - top;
    this.clampScroll();
    this.emitUpdate();
  }

  /** Case-insensitive matches of `query` in scrollback + screen (max 2000). */
  find(query: string): { line: number; col: number; len: number }[] {
    if (!query) return [];
    const q = query.toLowerCase();
    const buf = this.xterm.buffer.active;
    const out: { line: number; col: number; len: number }[] = [];
    for (let y = 0; y < buf.length && out.length < 2000; y++) {
      const text = buf.getLine(y)?.translateToString(false).toLowerCase() ?? "";
      for (let i = text.indexOf(q); i !== -1 && out.length < 2000; i = text.indexOf(q, i + Math.max(1, q.length))) {
        out.push({ line: y, col: i, len: q.length });
      }
    }
    return out;
  }

  /** Text of the visible screen, trailing blank lines removed. */
  getVisibleText(): string {
    return this.getLines(this.viewportTop, this.xterm.rows);
  }

  /** Whole scrollback + screen as text. */
  getAllText(): string {
    const buf = this.xterm.buffer.active;
    return this.getLines(0, buf.length);
  }

  private getLines(start: number, count: number): string {
    const buf = this.xterm.buffer.active;
    const lines: string[] = [];
    for (let y = start; y < Math.min(buf.length, start + count); y++) {
      const line = buf.getLine(y);
      const text = line?.translateToString(true) ?? "";
      // Soft-wrapped lines are continuations of the previous one.
      if (line?.isWrapped && lines.length) lines[lines.length - 1] += text;
      else lines.push(text);
    }
    while (lines.length && lines[lines.length - 1] === "") lines.pop();
    return lines.join("\n");
  }

  onUpdate(l: Listener) { this.updateListeners.add(l); return () => this.updateListeners.delete(l); }
  onExit(l: Listener<[number | null]>) { this.exitListeners.add(l); return () => this.exitListeners.delete(l); }
  onTitle(l: Listener<[string]>) { this.titleListeners.add(l); return () => this.titleListeners.delete(l); }
  onStatus(l: Listener) { this.statusListeners.add(l); return () => this.statusListeners.delete(l); }
  onBell(l: Listener) { this.bellListeners.add(l); return () => this.bellListeners.delete(l); }

  dispose() {
    if (this.disposed) return;
    this.disposed = true;
    this.updateListeners.clear();
    this.exitListeners.clear();
    this.titleListeners.clear();
    this.bellListeners.clear();
    this.statusListeners.clear();
    try { this.proc?.kill(); } catch {}
    try { this.proc?.terminal?.close(); } catch {}
    this.xterm.dispose();
  }
}
